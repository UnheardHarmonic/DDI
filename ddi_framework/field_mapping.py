# 构建小写键索引用于大小写无关的兜底查询。
_LOWER_KEY_INDEX = {str(key).lower(): key for key in FIELD_TITLE_MAPPING}


# 判断文本是否包含中文字符。
def _has_cjk(text):

    """
    判断文本中是否包含中文字符。

    :param text: 待判断文本。
    :type text: str
    :return: 包含中文返回真值。
    :rtype: bool
    """

    # 遍历字符判断中文区段。
    for char in str(text):
        if "一" <= char <= "鿿":
            return True

    # 无中文返回假值。
    return False


# 解析原始字段的中文标题。
def resolve_field_title(key, current_title=None):

    """
    解析原始字段键的中文标题，标题已含中文时保持原样。

    规则：字段键命中映射表且现标题不含中文时返回映射中文；否则返回现
    标题或字段键本身，保证服务端中文标题不被覆盖。

    :param key: 原始字段键。
    :type key: str
    :param current_title: 现有标题文本。
    :type current_title: str | None
    :return: 解析后的标题文本。
    :rtype: str
    """

    # 规范化字段键与现标题。
    key_text = str(key or "").strip()
    title_text = str(current_title or "").strip()

    # 判断现标题已含中文时保持原样。
    if _has_cjk(title_text):
        return title_text

    # 精确命中映射表。
    if key_text in FIELD_TITLE_MAPPING:
        return FIELD_TITLE_MAPPING[key_text]

    # 小写兜底命中映射表。
    lower_key = _LOWER_KEY_INDEX.get(key_text.lower())
    if lower_key:
        return FIELD_TITLE_MAPPING[lower_key]

    # 返回现标题或字段键。
    return title_text or key_text
